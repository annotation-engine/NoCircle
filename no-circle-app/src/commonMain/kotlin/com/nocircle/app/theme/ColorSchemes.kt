sealed interface ColorSchemes {
	
	val lightColorScheme: ColorScheme
	
	val darkColorScheme: ColorScheme
}

object DefaultColorSchemes : ColorSchemes {
	
	override val lightColorScheme by lazy { LightScheme }
	
	override val darkColorScheme by lazy { DarkScheme }
}

object MediumContrastColorSchemes : ColorSchemes {
	
	override val lightColorScheme by lazy { MediumContrastLightColorScheme }
	
	override val darkColorScheme by lazy { MediumContrastDarkColorScheme }
}

object HighContrastColorSchemes : ColorSchemes {
	
	override val lightColorScheme by lazy { HighContrastLightColorScheme }
	
	override val darkColorScheme by lazy { HighContrastDarkColorScheme }
}